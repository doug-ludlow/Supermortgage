/**
 * Write the deterministic 100-loan demo transfer batch to fixtures/transfer-batch-demo/:
 * the transferor's tape files (1.1 "Inputs and triggers"), the two external
 * positions the DQ gate reads, a manifest with every file's SHA-256 (the
 * idempotency key `ingestTape` uses) and LAYOUT.md, the column dictionary.
 *
 *   node --experimental-strip-types tools/gen-transfer-batch.ts [out-dir]
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateDemoBatch, DEMO_BATCH } from "../src/domain/boarding/demo-batch.ts";
import { encodeTransferBatch, FINAL_TAPE_COLUMNS, PAYMENT_HISTORY_HEADER, ESCROW_HISTORY_HEADER, ESCROW_ANALYSIS_HEADER, LOSSMIT_HEADER, FC_BK_HEADER, CONSENTS_HEADER, IMAGES_HEADER, TRIAL_BALANCE_HEADER, FNMA_POSITION_HEADER, MERS_LOOKUP_HEADER, FAIR_LENDING_HEADER } from "../src/domain/boarding/tape-codec.ts";

const out = process.argv[2] ?? fileURLToPath(new URL("../fixtures/transfer-batch-demo/", import.meta.url));
mkdirSync(out, { recursive: true });
const batch = generateDemoBatch();
const files = encodeTransferBatch(batch, batch.coborrowers);
const sha = (s: string): string => createHash("sha256").update(s).digest("hex");
const rowsOf = (csv: string): number => csv.split("\n").filter((l) => l.length).length - 1;

const manifest = {
  batch: { ...DEMO_BATCH, upb_total: batch.loans.reduce((s, l) => s + (l.upb_cents ?? 0n), 0n).toString(), escrow_total: batch.loans.reduce((s, l) => s + l.escrow_balance_cents, 0n).toString() },
  generated_by: "tools/gen-transfer-batch.ts (deterministic; seed above)",
  files: Object.fromEntries(Object.entries(files).map(([name, text]) => [name, { sha256: sha(text), row_count: rowsOf(text), bytes: Buffer.byteLength(text) }])),
  designed_outcomes: { hard: Object.fromEntries([...batch.designed.hard].map(([k, v]) => [k, [...v]])), warnings: Object.fromEntries([...batch.designed.warnings].map(([k, v]) => [k, [...v]])) },
};
for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text);
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

const table = (cols: readonly string[]): string => `| Column |\n|---|\n${cols.map((c) => `| \`${c}\` |`).join("\n")}\n`;
const layout = `# Demo transfer batch — tape layout

A deterministic 100-loan servicing-transfer package for the October 1, 2026 transfer of
${DEMO_BATCH.transferor_name} (transferor servicer ${DEMO_BATCH.transferor_servicer_number}) to
Supermortgage (servicer ${DEMO_BATCH.partner_servicer_number}), regenerated by
\`node --experimental-strip-types tools/gen-transfer-batch.ts\`. Every person, address and
identifier is synthetic (TINs use the never-issued 000 area number); every balance is derived
from the loan's own terms and payment history, so the 1.1 data-quality gate can be run on it
end to end. \`manifest.json\` carries each file's SHA-256 (the idempotency key of
\`transfer.tape.received\`) and the defects the generator plants.

Files (spec 1.1 "Inputs and triggers"; \`kind\` is the \`boarding_tapes.kind\` value):

| File | kind | One row per |
|---|---|---|
| \`boarding_tape.final.csv\` | final | loan (close of business T−1) |
| \`payment_history.csv\` | payment_history | scheduled installment, with the receipt that satisfied it (FIFO) |
| \`escrow_history.csv\` | escrow_history | escrow line |
| \`escrow_analysis.csv\` | escrow_analysis | escrowed loan (last analysis, balance, sign check) |
| \`lossmit_file.csv\` | lossmit | loan with loss mitigation in process |
| \`fc_bk_file.csv\` | fc_bk | loan in bankruptcy or foreclosure |
| \`consents_file.csv\` | consents | loan (E-SIGN and TCPA evidence flags) |
| \`images_manifest.csv\` | images_manifest | document image (note, mortgage, title policy, allonge, deferral agreement) |
| \`trial_balance.csv\` | trial_balance | loan (F-1-11 trial balance as of T−1) |
| \`fnma_position.csv\` | (LSDU Master Servicing Loan Position pull) | loan |
| \`mers_lookup.csv\` | (MERS MIN lookup) | registered MIN |
| \`fair_lending.csv\` | (F-1-11 fair-lending elements; restricted table \`borrower_fair_lending\`) | loan with data |

## boarding_tape.final.csv

Money is a decimal dollar string (negative allowed); dates are ISO 8601; booleans are Y/N; an
empty cell is null. The MISMO path is the illustrative canonical path the mapping set targets
(\`boarding_staging.canonical_path\`); the per-transferor \`mapping_rules\` set decides the real one.

| Column | MISMO v3.6 path (illustrative) | Canonical field | Read by |
|---|---|---|---|
${FINAL_TAPE_COLUMNS.map((c) => `| \`${c.column}\` | \`${c.mismo}\` | \`${c.field}\` | ${c.rules} |`).join("\n")}

## Detail files

payment_history.csv — \`received_on\`/\`received_amount\` empty = installment unpaid as of T−1.
${table(PAYMENT_HISTORY_HEADER)}
escrow_history.csv — \`line_type\` ∈ county_tax, hazard, flood, mi; \`annual_amount\` in dollars.
${table(ESCROW_HISTORY_HEADER)}
escrow_analysis.csv — \`balance_sign_consistent\` N = the history contradicts the balance sign (HF-007).
${table(ESCROW_ANALYSIS_HEADER)}
lossmit_file.csv
${table(LOSSMIT_HEADER)}
fc_bk_file.csv
${table(FC_BK_HEADER)}
consents_file.csv
${table(CONSENTS_HEADER)}
images_manifest.csv — \`sha256\` of the image file the transferor delivers alongside.
${table(IMAGES_HEADER)}
trial_balance.csv
${table(TRIAL_BALANCE_HEADER)}
fnma_position.csv — \`scheduled_upb\` only for S/S loans.
${table(FNMA_POSITION_HEADER)}
mers_lookup.csv
${table(MERS_LOOKUP_HEADER)}
fair_lending.csv — restricted; access-logged; retention life_of_loan_plus_4y.
${table(FAIR_LENDING_HEADER)}
## Designed outcomes

Hard failures (cannot board until corrected or, for a non-money field, officer-waived):

${[...batch.designed.hard].map(([n, codes]) => `- \`${n}\`: ${codes.join(", ")}`).join("\n")}

Warnings (board with an open exception): ${batch.designed.warnings.size} loans; the full list is in \`manifest.json\`.
`;
writeFileSync(join(out, "LAYOUT.md"), layout);
console.log(`wrote ${Object.keys(files).length + 2} files to ${out}: ${batch.loans.length} loans, ${batch.designed.hard.size} with hard failures, ${batch.designed.warnings.size} with warnings`);
